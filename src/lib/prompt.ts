// Модель размечает тему первой строкой ("ТЕМА: <тег>" или "ТЕМА: <тег1>,
// <тег2>", см. CATEGORY_INSTRUCTIONS в SUMMARY_PROMPT) — отделяем её от
// текста самого саммари. Не больше 2 тегов (см. CATEGORY_INSTRUCTIONS) —
// лишние отбрасываем, а не молча теряем всю разметку. Если строки нет
// (например, это ответ на CATEGORY_ONLY_PROMPT, который вместо этого
// возвращает голый тег без разметки)
// — просто возвращаем текст как есть с category: null.
export function extractCategory(text: string): { category: Category[] | null; summary: string } {
  const match = text.match(/^\s*ТЕМА\s*:\s*([^\n]+)\n+([\s\S]*)$/iu);
  if (!match) return { category: null, summary: text };
  const tags = match[1]
    .split(/[,;/]+/)
    // теги всегда простые латинские слова — срезаем случайную пунктуацию
    // по краям (точку, кавычки и т.п.), которую модель иногда добавляет.
    .map((t) => t.trim().toLowerCase().replace(/[^a-z]/g, ""))
    .filter((t): t is Category => (ALL_TAGS as readonly string[]).includes(t));
  const unique = Array.from(new Set(tags)).slice(0, 2);
  return { category: unique.length ? unique : null, summary: match[2].trim() };
}

// Модель просит показать другой источник контекста вместо навигационного
// мусора/пустой страницы — единственный ответ, который код умеет отличить от
// настоящего саммари (см. SUMMARY_PROMPT). Раньше при плохом контексте модель
// писала по-русски "в тексте отсутствуют факты, пришлите материал" — и это
// сохранялось в базу как саммари, показывалось пользователю. Теперь такой
// ответ — явный сигнал переключиться на более простой источник контекста
// (см. summarizeArticle в src/lib/summarizer.ts).
export function isNoContentSignal(text: string): boolean {
  return text.trim().toUpperCase().startsWith("NO_CONTENT");
}

// Модели иногда всё равно упираются в лимит токенов на середине предложения.
// Если ответ обрывается без финальной пунктуации — подрезаем до последнего
// целого предложения, чтобы в ленте не было висящих обрывков фраз.
export function ensureCompleteSentence(text: string): string {
  const trimmed = text.trim();
  if (/[.!?…»"]$/.test(trimmed)) return trimmed;

  const lastEnd = Math.max(
    trimmed.lastIndexOf(". "),
    trimmed.lastIndexOf("! "),
    trimmed.lastIndexOf("? "),
    trimmed.lastIndexOf(".\n")
  );
  if (lastEnd > 20) return trimmed.slice(0, lastEnd + 1);

  // Ни одного завершённого предложения не нашлось — лучше вернуть как есть,
  // чем откусить вообще всё.
  return trimmed;
}
