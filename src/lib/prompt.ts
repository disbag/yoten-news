// Разбирает ответ на LEAD_AND_MORE_PROMPT (уже без строки ТЕМА — её снимает
// extractCategory). Без разделителя — весь текст считаем главным, без ката.
// Продолжение длиннее 200 слов (модель не всегда держит лимит) подрезаем до
// последнего целого предложения в пределах лимита.
const MORE_MAX_WORDS = 200;
export function splitLeadAndMore(text: string): { lead: string; more: string | null } {
  const [leadRaw, ...rest] = text.split(/\n\s*===\s*(?:\n|$)/);
  const strip = (t: string) => t.replace(/^\s*(главное|подробности|часть\s*\d)\s*[:—-]\s*/iu, "").trim();
  const lead = ensureCompleteSentence(strip(leadRaw));
  let more = strip(rest.join("\n"));
  if (!more) return { lead, more: null };

  const words = more.split(/\s+/);
  if (words.length > MORE_MAX_WORDS) {
    const cut = words.slice(0, MORE_MAX_WORDS).join(" ");
    const lastEnd = Math.max(cut.lastIndexOf(". "), cut.lastIndexOf("! "), cut.lastIndexOf("? "));
    more = lastEnd > 0 ? cut.slice(0, lastEnd + 1) : cut;
  }
  return { lead, more: ensureCompleteSentence(more) };
}

